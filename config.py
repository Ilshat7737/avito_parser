import os

from dotenv import load_dotenv

load_dotenv()

# Ссылка на страницу поиска Avito.
# Проще всего: откройте avito.ru, настройте фильтры (город, категория, цена и т.д.)
# и скопируйте адрес из строки браузера сюда.
