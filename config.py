# Как часто проверять (в секундах). Не ставьте слишком маленький интервал —
# частые запросы повышают риск блокировки по IP.
CHECK_INTERVAL_SEC = 60  # 1 минута — осознанный риск, см. спеку раздел
                          # "Осознанно принятый риск: интервал в 1 минуту"

# Случайный разброс к интервалу (секунды), чтобы запросы шли не строго по расписанию
INTERVAL_JITTER_SEC = 60

# Подгружать ли полное описание для НОВЫХ объявлений (это доп. запрос
# на страницу самого объявления, только для новых карточек)
FETCH_FULL_DESCRIPTION = True

# Путь к файлу базы данных (создастся автоматически)
DB_PATH = "avito_monitor.db"

# Отдельная БД для веб-режима (app.py) — не должна пересекаться с CLI-режимом
# (main.py), у которого нет ни таблицы seen_ids, ни обрезки по 100 строк;
# общая БД привела бы к порче лимита/dedup веб-режима записями из CLI и
# наоборот.
WEB_DB_PATH = os.environ.get("WEB_DB_PATH", "avito_monitor_web.db")

# Порт веб-интерфейса (app.py). НЕ 5000 по умолчанию — на macOS (Monterey и
# новее) порт 5000 системно занят AirPlay Receiver, который отвечает
# браузеру 403 Forbidden вместо нашего Flask-приложения.
WEB_PORT = int(os.environ.get("WEB_PORT", "5050"))

# False = показывать окно браузера. Так Avito реже считает сессию ботом,
# чем в headless-режиме.
HEADLESS = False

# Задержки между запросами страниц (секунды) — имитация человека и защита
# от блокировки по IP. Не чаще 1 запроса к странице раз в 20 сек — прямая
# просьба пользователя после столкновения с ограничениями по IP.
